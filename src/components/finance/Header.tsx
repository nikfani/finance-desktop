export function Header() {
  const [tipIndex, setTipIndex] = useState(() => Math.floor(Math.random() * STATUS_LINES.length));

  useEffect(() => {
    const getRandomIndex = (current: number) => {
      if (STATUS_LINES.length <= 1) return 0;
      let next = current;
      while (next === current) {
        next = Math.floor(Math.random() * STATUS_LINES.length);
      }
      return next;
    };

    const timer = setInterval(() => {
      setTipIndex((current) => getRandomIndex(current));
    }, 60000);

    return () => clearInterval(timer);
  }, []);

  const line = STATUS_LINES[tipIndex].author
    ? `${STATUS_LINES[tipIndex].text} — ${STATUS_LINES[tipIndex].author}`
    : STATUS_LINES[tipIndex].text;

  return (
    <header className="h-24 bg-white border-b border-[var(--border)] px-8 lg:px-10 flex items-center">
      <div className="min-w-0 w-full">
        <p className="w-full text-center whitespace-nowrap overflow-hidden text-ellipsis text-[13px] md:text-[15px] font-normal text-[var(--text-secondary)] leading-normal">
          {line}
        </p>
      </div>
    </header>
  );
}
